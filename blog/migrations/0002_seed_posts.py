        if not BlogPost.objects.filter(slug=slug).exists():
            BlogPost.objects.create(
                title=post['title'],
                slug=slug,
                excerpt=post['excerpt'],
                body=post['body'],
                is_published=True,
                published_at=now - timezone.timedelta(days=(len(POSTS) - offset) * 3),
            )


